export function parseAnswers(value: string | undefined): number[] | null {
  if (!value) return null;
  try {
    const parsed = JSON.parse(value);
    if (!Array.isArray(parsed) || parsed.length !== QUESTIONS.length) return null;
    return parsed.map((n) => Number(n) || 0);
  } catch {
    return null;
  }
}

export function scoreQuiz(answers: number[]): {
  type: AttachmentType;
  breakdown: { type: TypeId; percent: number }[];
} {
  const tally: Record<TypeId, number> = { anxious: 0, avoidant: 0, secure: 0 };

  answers.forEach((choice, i) => {
    const option = QUESTIONS[i]?.options[choice];
    if (option) tally[option.type] += 1;
  });

  const total = answers.length || 1;
  let best: TypeId = 'secure';
  for (const key of Object.keys(tally) as TypeId[]) {
    if (tally[key] > tally[best]) best = key;
  }

  const breakdown = (Object.keys(tally) as TypeId[]).map((type) => ({
    type,
    percent: Math.round((tally[type] / total) * 100),
  }));

  return { type: TYPES[best], breakdown };
}

export function pdfTitle(userData: UserData): string {
  const answers = parseAnswers(userData.answers);
  if (!answers) return SITE.name;
  return `Тип привязанности — ${scoreQuiz(answers).type.name}`;
}

export function buildSections(userData: UserData, plan: PlanId): Section[] {
  const answers = parseAnswers(userData.answers);

  if (!answers) {
    return [
      {
        title: 'Данные не распознаны',
        content: 'Не удалось прочитать ответы теста. Вернитесь на сайт и пройдите тест заново.',
      },
    ];
  }

  const { type, breakdown } = scoreQuiz(answers);
  const sections: Section[] = [];

  sections.push({
    title: 'Тип привязанности партнёра',
    content: `${type.name} тип привязанности.\n\n${type.description}`,
  });

  sections.push({
    title: 'Распределение по типам',
    content: breakdown
      .map((b) => `${TYPES[b.type].name}: ${b.percent}%`)
      .join('\n'),
  });

  sections.push({ title: 'Ключевая черта', content: type.keyTrait });

  if (plan === 'full' || plan === 'premium') {
    sections.push({ title: 'Почему он или она ведёт себя именно так', content: type.why });
    sections.push({ title: 'Что запускает такую реакцию', content: type.triggers });
    sections.push({ title: 'Как общаться с этим типом', content: type.howTo });
    sections.push({ title: 'Чего делать не стоит', content: type.avoid });
  }

  if (plan === 'premium') {
    sections.push({ title: 'Стратегия общения на 30 дней', content: type.plan30 });
    sections.push({ title: 'Скрипты для сложных разговоров', content: type.scripts });
    sections.push({ title: 'Долгосрочный прогноз', content: type.longTerm });
  }

  sections.push({
    title: 'О документе',
    content: `Тариф: ${PLAN_LABELS[plan]}. Материал носит развлекательный и просветительский характер. Теория привязанности описывает тенденции, а не диагнозы: это не психологическое заключение и не заменяет консультацию специалиста.`,
  });

  return sections;
}
